    <script>
        (function () {
            // ----- Lightbox (fallback: your full site already has these) -----
            window.openLightbox = window.openLightbox || function (src, title, desc) {
                document.getElementById('lightbox-img').src = src;
                document.getElementById('lightbox-title').textContent = title;
                document.getElementById('lightbox-desc').textContent = desc;
                const m = document.getElementById('lightbox-modal');
                m.classList.remove('hidden'); m.classList.add('flex');
            };
            window.closeLightbox = window.closeLightbox || function () {
                const m = document.getElementById('lightbox-modal');
                m.classList.add('hidden'); m.classList.remove('flex');
            };
            document.addEventListener('keydown', (e) => { if (e.key === 'Escape') window.closeLightbox(); });

            // ----- Carousel -----
            const viewport = document.getElementById('gal-viewport');
            const track = document.getElementById('gal-track');
            const originals = Array.from(track.children);
            const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

            // Extra copies so the loop never shows a gap (only as many as the screen needs)
            function addSet() {
                originals.forEach((n) => {
                    const k = n.cloneNode(true);
                    k.setAttribute('aria-hidden', 'true');
                    k.tabIndex = -1;
                    track.appendChild(k);
                });
            }
            addSet(); addSet();

            let setW = 0, cardStep = 0;
            let pos = 0, target = null;
            let paused = false, dragging = false, moved = 0, startX = 0, startPos = 0;
            let inView = false;
            let speed = 0, drawn = null, scrolling = false, scrollTimer = null;

            function measure() {
                const first = track.children[0];
                const next = track.children[originals.length];
                const oldSetW = setW;
                setW = next.offsetLeft - first.offsetLeft;
                const sets = track.children.length / originals.length;
                const need = Math.ceil(viewport.clientWidth / setW) + 2;
                for (let k = sets; k < need; k++) addSet();
                cardStep = track.children[1].offsetLeft - first.offsetLeft;
                pos = oldSetW ? (pos / oldSetW) * setW : setW; // start in the second copy
            }
            function wrap() {
                while (pos >= 2 * setW) { pos -= setW; if (target !== null) target -= setW; }
                while (pos < setW)      { pos += setW; if (target !== null) target += setW; }
            }
            function render() {
                // snap to device pixels: no sub-pixel shimmer, and skip the write if nothing moved
                const dpr = window.devicePixelRatio || 1;
                const x = Math.round(pos * dpr) / dpr;
                if (x === drawn) return;
                drawn = x;
                track.style.transform = 'translate3d(' + (-x) + 'px,0,0)';
            }

            measure(); render();
            window.addEventListener('load', () => { measure(); render(); });
            window.addEventListener('resize', () => { measure(); render(); });

            new IntersectionObserver((e) => { inView = e[0].isIntersecting; }, { threshold: 0 }).observe(viewport);

            // Auto-scroll + eased arrows
            let last = performance.now();
            function tick(t) {
                const dt = Math.min(t - last, 50); last = t;
                if (inView && setW) {
                    if (target !== null) {
                        const d = target - pos;
                        pos += d * 0.12;
                        if (Math.abs(d) < 0.5) { pos = target; target = null; }
                    } else {
                        // glide toward ~35px/s, or toward 0 while hovering, dragging or while the page scrolls
                        const goal = (!paused && !dragging && !scrolling && !reduce) ? 0.035 : 0;
                        speed += (goal - speed) * 0.06;
                        pos += dt * speed;
                    }
                    wrap(); render();
                }
                requestAnimationFrame(tick);
            }
            requestAnimationFrame(tick);

            // While the page itself is scrolling, hold the carousel still (no competing motion)
            window.addEventListener('scroll', () => {
                scrolling = true;
                clearTimeout(scrollTimer);
                scrollTimer = setTimeout(() => { scrolling = false; }, 200);
            }, { passive: true });

            // Drag / swipe
            viewport.addEventListener('pointerdown', (e) => {
                if (e.pointerType === 'mouse' && e.button !== 0) return;
                dragging = true; moved = 0; startX = e.clientX; startPos = pos; target = null;
                viewport.classList.add('grabbing');
            });
            window.addEventListener('pointermove', (e) => {
                if (!dragging) return;
                const dx = e.clientX - startX;
                moved = Math.max(moved, Math.abs(dx));
                pos = startPos - dx;
            });
            const endDrag = () => { dragging = false; viewport.classList.remove('grabbing'); };
            window.addEventListener('pointerup', endDrag);
            window.addEventListener('pointercancel', endDrag);

            // Pause on hover / keyboard focus
            viewport.addEventListener('mouseenter', () => { paused = true; });
            viewport.addEventListener('mouseleave', () => { paused = false; });
            viewport.addEventListener('focusin', () => { paused = true; });
            viewport.addEventListener('focusout', () => { paused = false; });

            // Click a card = open lightbox (ignored if it was a drag)
            viewport.addEventListener('click', (e) => {
                if (moved > 6) { moved = 0; return; }
                const card = e.target.closest('.gal-card');
                if (card) window.openLightbox(card.dataset.src, card.dataset.title, card.dataset.desc);
            });

            // Arrows
            document.getElementById('gal-prev').addEventListener('click', () => { target = (target === null ? pos : target) - cardStep; });
            document.getElementById('gal-next').addEventListener('click', () => { target = (target === null ? pos : target) + cardStep; });

            // One reveal when the section first comes into view
            const revealEls = [document.getElementById('gal-head'), viewport];
            revealEls.forEach((el) => el.classList.add('gal-reveal'));
            const io = new IntersectionObserver((entries) => {
                entries.forEach((en) => {
                    if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
                });
            }, { threshold: 0.15 });
            revealEls.forEach((el, i) => { el.style.transitionDelay = (i * 0.15) + 's'; io.observe(el); });
        })();
    </script>

    
